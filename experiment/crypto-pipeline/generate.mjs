// Step 2 — generate Paperback-safe native TS from constants.json.
//
// Emits:
//   src/ComixTo/ComixFastDecrypt.ts  — fastDecryptComixPayload(path, payload, headers)
//   src/ComixTo/ComixFastSigner.ts   — fastGenerateHash(rawPath)
//
// Both are self-contained, JavaScriptCore-safe (no Node/DOM/crypto APIs), and
// embed the constants. Decrypt applies inverse stages 1..N; sign applies forward
// stages N..1 (the cipher is symmetric — same triples both ways).
//
//   node experiment/crypto-pipeline/generate.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT } from "./lib.mjs";

const CONSTANTS = resolve(ROOT, "experiment/crypto-pipeline/constants.json");
const DECRYPT_OUT = resolve(ROOT, "src/ComixTo/ComixFastDecrypt.ts");
const SIGNER_OUT = resolve(ROOT, "src/ComixTo/ComixFastSigner.ts");

// Shared helpers embedded verbatim into both generated files. Kept as a raw
// string so what we test (Step 3) is exactly what ships.
const SHARED = String.raw`const B64_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

function b64Decode(s: string): number[] {
    const lookup: number[] = new Array(128).fill(-1);
    for (let i = 0; i < 64; i++) lookup[B64_CHARS.charCodeAt(i)] = i;
    const normalized = s.replace(/-/g, "+").replace(/_/g, "/");
    const out: number[] = [];
    let buf = 0, bits = 0;
    for (let i = 0; i < normalized.length; i++) {
        const c = normalized.charCodeAt(i);
        if (c === 61) break; // '='
        const v = lookup[c] ?? -1;
        if (v < 0) continue;
        buf = (buf << 6) | v;
        bits += 6;
        if (bits >= 8) { bits -= 8; out.push((buf >> bits) & 0xff); }
    }
    return out;
}

// Inverse-permutation cache, keyed by the stage's forward S-box base64.
const INV_CACHE: Record<string, number[]> = {};
function inverseSbox(tableB64: string): number[] {
    const cached = INV_CACHE[tableB64];
    if (cached) return cached;
    const table = b64Decode(tableB64);
    const inv: number[] = new Array(256).fill(0);
    for (let i = 0; i < 256; i++) inv[table[i]!] = i;
    INV_CACHE[tableB64] = inv;
    return inv;
}
const KEY_CACHE: Record<string, number[]> = {};
function keyBytes(keyB64: string): number[] {
    const cached = KEY_CACHE[keyB64];
    if (cached) return cached;
    const k = b64Decode(keyB64);
    KEY_CACHE[keyB64] = k;
    return k;
}`;

function genDecrypt(c) {
  const stages = JSON.stringify(c.stages.map((s) => ({ sboxB64: s.sboxB64, keyB64: s.keyB64, iv: s.iv })), null, 4);
  return `/* Generated by experiment/crypto-pipeline/generate.mjs. DO NOT EDIT BY HAND.
 * Bundle ID: ${c.bundleId}
 * Algorithm: ${c.algorithm}-inverse (response decrypt), ${c.rounds} rounds.
 * Round: out[i] = invSbox[in[i]] ^ in[i-1] ^ key[i % key.length]   (in[-1] = iv)
 * Applied for stages 1..N. Verified byte-exact against the live bundle.
 */

${SHARED}

const DECRYPT_STAGES: { sboxB64: string; keyB64: string; iv: number }[] = ${stages};

function decryptRound(data: number[], sboxB64: string, keyB64: string, iv: number): number[] {
    const inv = inverseSbox(sboxB64);
    const key = keyBytes(keyB64);
    const out: number[] = new Array(data.length);
    let prev = iv & 0xff;
    for (let i = 0; i < data.length; i++) {
        const c = data[i]! & 0xff;
        out[i] = (inv[c]! ^ prev ^ key[i % key.length]!) & 0xff;
        prev = c;
    }
    return out;
}

// Manual UTF-8 decode (JavaScriptCore-safe; no TextDecoder dependency).
function utf8Decode(bytes: number[]): string {
    let out = "";
    let i = 0;
    const n = bytes.length;
    while (i < n) {
        const b = bytes[i++]! & 0xff;
        if (b < 0x80) {
            out += String.fromCharCode(b);
        } else if (b < 0xe0) {
            out += String.fromCharCode(((b & 0x1f) << 6) | (bytes[i++]! & 0x3f));
        } else if (b < 0xf0) {
            const b1 = bytes[i++]! & 0x3f, b2 = bytes[i++]! & 0x3f;
            out += String.fromCharCode(((b & 0x0f) << 12) | (b1 << 6) | b2);
        } else {
            const b1 = bytes[i++]! & 0x3f, b2 = bytes[i++]! & 0x3f, b3 = bytes[i++]! & 0x3f;
            let cp = ((b & 0x07) << 18) | (b1 << 12) | (b2 << 6) | b3;
            cp -= 0x10000;
            out += String.fromCharCode(0xd800 + (cp >> 10), 0xdc00 + (cp & 0x3ff));
        }
    }
    return out;
}

function normalizeHeaders(headers: Record<string, string>): Record<string, string> {
    const out: Record<string, string> = {};
    for (const key of Object.keys(headers ?? {})) out[key.toLowerCase()] = String(headers[key]);
    return out;
}

/**
 * Decrypt a comix.to encrypted API envelope ({ e: "<base64>" }) to its parsed
 * result. Pass-through when the payload is not encrypted. Mirrors the bundle's
 * response interceptor, including the { status: "ok", result } unwrap.
 */
export function fastDecryptComixPayload(rawPath: string, payload: any, headers: Record<string, string> = {}): any {
    void rawPath;
    if (!(payload && typeof payload === "object" && typeof payload.e === "string")) return payload;
    const h = normalizeHeaders(headers);
    if (h["x-enc"] && h["x-enc"] !== "1") return payload;

    let data = b64Decode(payload.e);
    for (const stage of DECRYPT_STAGES) data = decryptRound(data, stage.sboxB64, stage.keyB64, stage.iv);

    const parsed = JSON.parse(utf8Decode(data));
    return parsed && typeof parsed === "object" && parsed.status === "ok" && "result" in parsed ? parsed.result : parsed;
}
`;
}

function genSigner(c) {
  const stages = JSON.stringify(c.stages.map((s) => ({ sboxB64: s.sboxB64, keyB64: s.keyB64, iv: s.iv })), null, 4);
  return `/* Generated by experiment/crypto-pipeline/generate.mjs. DO NOT EDIT BY HAND.
 * Bundle ID: ${c.bundleId}
 * Algorithm: ${c.algorithm} (request signer), ${c.rounds} rounds.
 * Round: out[i] = sbox[in[i] ^ out[i-1] ^ key[i % key.length]]   (out[-1] = iv)
 * Applied for stages N..1 (reverse of decrypt). Verified against the live token.
 */

${SHARED}

const SIGN_STAGES: { sboxB64: string; keyB64: string; iv: number }[] = ${stages};

function signRound(data: number[], sboxB64: string, keyB64: string, iv: number): number[] {
    const table = b64Decode(sboxB64);
    const key = keyBytes(keyB64);
    const out: number[] = new Array(data.length);
    let prev = iv & 0xff;
    for (let i = 0; i < data.length; i++) {
        const idx = ((data[i]! & 0xff) ^ prev ^ key[i % key.length]!) & 0xff;
        const next = table[idx]! & 0xff;
        out[i] = next;
        prev = next;
    }
    return out;
}

function b64UrlEncode(bytes: number[]): string {
    let out = "", i = 0;
    for (; i + 2 < bytes.length; i += 3) {
        const n = (bytes[i]! << 16) | (bytes[i + 1]! << 8) | bytes[i + 2]!;
        out += B64_CHARS[(n >> 18) & 63]! + B64_CHARS[(n >> 12) & 63]! + B64_CHARS[(n >> 6) & 63]! + B64_CHARS[n & 63]!;
    }
    if (i + 1 === bytes.length) {
        const n = bytes[i]! << 16;
        out += B64_CHARS[(n >> 18) & 63]! + B64_CHARS[(n >> 12) & 63]!;
    } else if (i + 2 === bytes.length) {
        const n = (bytes[i]! << 16) | (bytes[i + 1]! << 8);
        out += B64_CHARS[(n >> 18) & 63]! + B64_CHARS[(n >> 12) & 63]! + B64_CHARS[(n >> 6) & 63]!;
    }
    return out.replace(/\\+/g, "-").replace(/\\//g, "_");
}

// Manual UTF-8 encode (JavaScriptCore-safe; the bundle signs UTF-8 bytes, so
// non-ASCII query values — e.g. a unicode search keyword — must be encoded as
// UTF-8, not truncated per UTF-16 code unit).
function utf8Encode(s: string): number[] {
    const out: number[] = [];
    for (let i = 0; i < s.length; i++) {
        let cp = s.charCodeAt(i);
        if (cp >= 0xd800 && cp <= 0xdbff && i + 1 < s.length) {
            const lo = s.charCodeAt(i + 1);
            if (lo >= 0xdc00 && lo <= 0xdfff) { cp = 0x10000 + ((cp - 0xd800) << 10) + (lo - 0xdc00); i++; }
        }
        if (cp < 0x80) { out.push(cp); }
        else if (cp < 0x800) { out.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f)); }
        else if (cp < 0x10000) { out.push(0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f)); }
        else { out.push(0xf0 | (cp >> 18), 0x80 | ((cp >> 12) & 0x3f), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f)); }
    }
    return out;
}

function decodeComponent(s: string): string {
    try { return decodeURIComponent(s.replace(/\\+/g, " ")); } catch (e) { void e; return s; }
}

// Reproduce the canonical query string the comix bundle signs (= what the server
// re-derives from the incoming request): qs.stringify with encode:false,
// arrayFormat:"indices", skipNulls:true, keys sorted by raw code unit. Reverse-
// engineered by decrypting live tokens (bundle 625d…) and fuzz-verified byte-exact
// vs the bundle across 3000 randomized param objects. Keys sort by base name (the
// part before the first "["), so a key and its array/nested children stay together;
// "name[]" arrays become "name[][0]=…&name[][1]=…" in document order (bundle
// 9afd… keeps the "[]"; earlier bundles stripped it to "name[0]="); nested keys
// ("order[number]") are kept verbatim; values are RAW (URL-decoded), never re-encoded.
function canonicalizeQuery(rawQuery: string): string {
    if (!rawQuery) { return ""; }
    const groups: Record<string, string[]> = {};
    const arrayCounts: Record<string, number> = {};
    const parts = rawQuery.split("&");
    for (let p = 0; p < parts.length; p++) {
        const part = parts[p]!;
        if (!part) { continue; }
        const eq = part.indexOf("=");
        const key = decodeComponent(eq >= 0 ? part.slice(0, eq) : part);
        const value = decodeComponent(eq >= 0 ? part.slice(eq + 1) : "");
        let base: string;
        let rendered: string;
        if (key.slice(-2) === "[]") {
            base = key.slice(0, -2);
            const i = arrayCounts[base] ?? 0;
            arrayCounts[base] = i + 1;
            rendered = key + "[" + i + "]=" + value;
        } else {
            const bracket = key.indexOf("[");
            base = bracket >= 0 ? key.slice(0, bracket) : key;
            rendered = key + "=" + value;
        }
        if (groups[base]) { groups[base]!.push(rendered); }
        else { groups[base] = [rendered]; }
    }
    return Object.keys(groups).sort().map((b) => groups[b]!.join("&")).join("&");
}

function signString(s: string): string {
    let data = utf8Encode(s);
    for (let r = SIGN_STAGES.length - 1; r >= 0; r--) {
        const st = SIGN_STAGES[r]!;
        data = signRound(data, st.sboxB64, st.keyB64, st.iv);
    }
    return b64UrlEncode(data);
}

/**
 * Produce the comix.to \`_\` signing token for an API request. Since bundle
 * 625d… the signature covers the path AND the canonicalized query params —
 * pathname-only tokens now get 403 "Invalid token.". Accepts a full URL or a
 * bare path, with or without a query string.
 */
export function fastGenerateHash(rawPath: string): string {
    const stripped = rawPath.replace(/^https?:\\/\\/[^/]+/, "").replace(/^\\/api\\/v1/, "");
    const qIdx = stripped.indexOf("?");
    if (qIdx < 0) { return signString(stripped); }
    const path = stripped.slice(0, qIdx);
    const canonical = canonicalizeQuery(stripped.slice(qIdx + 1));
    return signString(canonical ? path + "?" + canonical : path);
}
`;
}

export function generate() {
  const c = JSON.parse(readFileSync(CONSTANTS, "utf8"));
  writeFileSync(DECRYPT_OUT, genDecrypt(c));
  writeFileSync(SIGNER_OUT, genSigner(c));
  return { decryptPath: DECRYPT_OUT, signerPath: SIGNER_OUT, bundleId: c.bundleId };
}

function main() {
  const r = generate();
  console.log(`[generate] bundle ${r.bundleId}`);
  console.log(`[generate] wrote ${r.decryptPath}`);
  console.log(`[generate] wrote ${r.signerPath}`);
}

